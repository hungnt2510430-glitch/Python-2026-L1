students = []
courses = []
marks = {}

def input_students():
    num_students = int(input("Enter number of students in class: "))
    for _ in range(num_students):
        print(f"\n--- Enter Student #{_ + 1} Information ---")
        student_id = input("Student ID: ")
        name = input("Student Name: ")
        dob = input("Date of Birth (DoB): ")
        students.append({"id": student_id, "name": name, "dob": dob})

def input_courses():
    num_courses = int(input("\nEnter number of courses: "))
    for _ in range(num_courses):
        print(f"\n--- Enter Course #{_ + 1} Information ---")
        course_id = input("Course ID: ")
        name = input("Course Name: ")
        courses.append({"id": course_id, "name": name})

def input_marks():
    if not courses:
        print("\nNo courses available. Please add courses first.")
        return
    if not students:
        print("\nNo students available. Please add students first.")
        return

    list_courses()
    course_id = input("\nSelect course ID to input marks for: ")

    course_exists = any(c['id'] == course_id for c in courses)
    if not course_exists:
        print("Course ID not found!")
        return

    if course_id not in marks:
        marks[course_id] = {}

    print(f"\n--- Inputting marks for Course ID: {course_id} ---")
    for student in students:
        mark = float(input(f"Enter mark for {student['name']} (ID: {student['id']}): "))
        marks[course_id][student['id']] = mark


def list_courses():
    print("\n================ List of Courses ================")
    if not courses:
        print("No courses available.")
        return
    for c in courses:
        print(f"ID: {c['id']} | Name: {c['name']}")

def list_students():
    print("\n================ List of Students ================")
    if not students:
        print("No students available.")
        return
    for s in students:
        print(f"ID: {s['id']} | Name: {s['name']} | DoB: {s['dob']}")

def show_student_marks():
    if not courses:
        print("\nNo courses available.")
        return

    course_id = input("\nEnter course ID to view marks: ")
    if course_id not in marks or not marks[course_id]:
        print("No marks recorded for this course ID.")
        return

    print(f"\n================ Marks for Course ID: {course_id} ================")
    for student in students:
        s_id = student['id']
        s_name = student['name']
        mark = marks[course_id].get(s_id, "N/A")
        print(f"ID: {s_id} | Name: {s_name} | Mark: {mark}")


def main():
    input_students()
    input_courses()

    while True:
        print("\n================ MENU ================")
        print("1. List courses")
        print("2. List students")
        print("3. Input marks for a course")
        print("4. Show student marks for a course")
        print("5. Exit")
        choice = input("Choose an option (1-5): ")

        if choice == '1':
            list_courses()
        elif choice == '2':
            list_students()
        elif choice == '3':
            input_marks()
        elif choice == '4':
            show_student_marks()
        elif choice == '5':
            print("Exiting program.")
            break
        else:
            print("Invalid option, please try again.")

if __name__ == "__main__":
    main()