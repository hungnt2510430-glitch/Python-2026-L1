class StudentMarkManagement:
    def __init__(self):
        self.__students = []
        self.__courses = []
        self.__marks = {}  # {course_id: {student_id: mark}}

    def add_student(self, student):
        self.__students.append(student)

    def add_course(self, course):
        self.__courses.append(course)

    def get_students(self):
        return self.__students

    def get_courses(self):
        return self.__courses

    def set_mark(self, course_id, student_id, mark):
        if course_id not in self.__marks:
            self.__marks[course_id] = {}
        floored_mark = math.floor(mark * 10) / 10.0
        self.__marks[course_id][student_id] = floored_mark

    def get_marks_for_course(self, course_id):
        return self.__marks.get(course_id, {})

    def calculate_gpa(self, student_id):
        student_marks = []
        course_credits = []

        for course in self.__courses:
            c_id = course.get_id()
            if c_id in self.__marks and student_id in self.__marks[c_id]:
                student_marks.append(self.__marks[c_id][student_id])
                course_credits.append(course.get_credit())

        if not course_credits:
            return 0.0

        marks_array = np.array(student_marks)
        credits_array = np.array(course_credits)

        weighted_sum = np.sum(marks_array * credits_array)
        total_credits = np.sum(credits_array)

        gpa = weighted_sum / total_credits
        return math.floor(gpa * 10) / 10.0

    def update_all_gpas(self):
        for student in self.__students:
            gpa = self.calculate_gpa(student.get_id())
            student.set_gpa(gpa)

    def sort_students_by_gpa(self):
        self.update_all_gpas()
        self.__students.sort(key=lambda s: s.get_gpa(), reverse=True)

